import mongoose from "mongoose";

/*
==================================================
ORDER ITEM SCHEMA
==================================================
*/

const orderItemSchema = new mongoose.Schema(
  {
    product: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Product",
      required: true,
    },

    name: {
      type: String,
      required: true,
      trim: true,
    },

    image: {
      type: String,
      default: "",
    },

    price: {
      type: Number,
      required: true,
      min: 0,
    },

    quantity: {
      type: Number,
      required: true,
      min: 1,
    },
  },
  {
    _id: false,
  }
);

/*
==================================================
SHIPPING ADDRESS SCHEMA
==================================================
*/

const shippingAddressSchema = new mongoose.Schema(
  {
    fullName: {
      type: String,
      required: true,
      trim: true,
    },

    phone: {
      type: String,
      required: true,
      trim: true,
    },

    address: {
      type: String,
      required: true,
      trim: true,
    },

    city: {
      type: String,
      required: true,
      trim: true,
    },

    state: {
      type: String,
      default: "",
      trim: true,
    },

    postalCode: {
      type: String,
      default: "",
      trim: true,
    },

    country: {
      type: String,
      default: "Pakistan",
      trim: true,
    },
  },
  {
    _id: false,
  }
);

/*
==================================================
ORDER SCHEMA
==================================================
*/

const orderSchema = new mongoose.Schema(
  {
    /*
    ----------------------------------------------
    USER
    ----------------------------------------------
    */

    user: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      index: true,
      required: false,
    },

    /*
    ----------------------------------------------
    ORDER ITEMS
    ----------------------------------------------
    */

    orderItems: {
      type: [orderItemSchema],

      required: true,

      validate: {
        validator: function (items) {
          return items.length > 0;
        },

        message: "Order must contain at least one product.",
      },
    },

    /*
    ----------------------------------------------
    SHIPPING ADDRESS
    ----------------------------------------------
    */

    shippingAddress: {
      type: shippingAddressSchema,
      required: true,
    },

    /*
    ----------------------------------------------
    PAYMENT METHOD
    ----------------------------------------------
    */

    paymentMethod: {
      type: String,

      enum: [
        "Cash on Delivery",
        "Easypaisa",
        "Card Payment",
        "Bank Transfer",
        "JazzCash",
      ],

      default: "Cash on Delivery",
    },

    /*
    ----------------------------------------------
    PAYMENT PROVIDER
    ----------------------------------------------
    */

    paymentProvider: {
      type: String,

      enum: [
        "COD",
        "EASYPAISA",
        "CARD",
        "BANK",
        "JAZZCASH",
        null,
      ],

      default: null,
    },

    /*
    ----------------------------------------------
    PAYMENT STATUS
    ----------------------------------------------
    */

    paymentStatus: {
      type: String,

      enum: [
        "Pending",
        "Paid",
        "Failed",
      ],

      default: "Pending",
    },

    /*
    ----------------------------------------------
    MERCHANT ORDER ID
    ----------------------------------------------
    
    This is generated by ShopHub.

    Example:
    SH-1758712345678-ABC123
    ----------------------------------------------
    */

    paymentOrderId: {
      type: String,

      default: "",

      index: true,
    },

    /*
    ----------------------------------------------
    GATEWAY TRANSACTION ID
    ----------------------------------------------
    
    This is returned by Easypaisa.

    Customer DOES NOT enter this manually.
    ----------------------------------------------
    */

    paymentTransactionId: {
      type: String,

      default: "",

      index: true,
    },

    /*
    ----------------------------------------------
    PAYMENT DATE
    ----------------------------------------------
    */

    paymentPaidAt: {
      type: Date,

      default: null,
    },

    /*
    ----------------------------------------------
    PAYMENT FAILURE REASON
    ----------------------------------------------
    */

    paymentFailureReason: {
      type: String,

      default: "",
    },

    /*
    ----------------------------------------------
    PRICE
    ----------------------------------------------
    */

    itemsPrice: {
      type: Number,

      required: true,

      min: 0,
    },

    shippingPrice: {
      type: Number,

      required: true,

      min: 0,

      default: 0,
    },

    totalPrice: {
      type: Number,

      required: true,

      min: 0,
    },

    /*
    ----------------------------------------------
    ORDER STATUS
    ----------------------------------------------
    */

    orderStatus: {
      type: String,

      enum: [
        "Pending",
        "Processing",
        "Shipped",
        "Delivered",
        "Cancelled",
      ],

      default: "Pending",
    },

    /*
    ----------------------------------------------
    DELIVERY
    ----------------------------------------------
    */

    isDelivered: {
      type: Boolean,

      default: false,
    },

    deliveredAt: {
      type: Date,

      default: null,
    },

    /*
    ----------------------------------------------
    CANCELLATION
    ----------------------------------------------
    */

    cancelledAt: {
      type: Date,

      default: null,
    },
  },

  {
    timestamps: true,
  }
);

const Order = mongoose.model("Order", orderSchema);

export default Order;